/* ---------------------------------------------------------------- catalogue */
async function json(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
}
const resolve = (base, href) => new URL(href, base).href;

/**
 * Learn what has been published.
 *
 * One request, not sixty-five. Walking the STAC catalogue means fetching the
 * catalogue, then 7 collections, then 56 items — 64 round trips before the first
 * pixel can be drawn. STAC's nested form is right for a catalogue somebody
 * browses with their own tools, and it is still published for exactly that; it is
 * the wrong shape for a page load, so the build also emits a flat index.
 *
 * The STAC walk stays as a fallback, so the viewer still works against a
 * `data/processed/` that predates the index.
 */
async function loadCatalog() {
  let index = null, indexUrl = null;
  for (const candidate of DATA_CANDIDATES) {
    try {
      indexUrl = new URL(`${candidate}/index.json`, location.href).href;
      index = await json(indexUrl);
      DATA = candidate;
      break;
    } catch { /* try the next layout */ }
  }
  if (index) {
    // Ground area per pixel by latitude, generated by raster.row_areas_m2. Without
    // it the readout cannot turn a pixel count into square kilometres, and it must
    // never work the value out for itself (CLAUDE.md #2), so its absence disables
    // the counting path rather than licensing a guess.
    state.areaTable = index.pixel_area_m2 || null;
    const out = {};
    for (const [id, layer] of Object.entries(index.layers)) {
      // One asset per layer: the map draws the whole archipelago from a single COG,
      // because OpenLayers cannot composite several GeoTIFF sources into one layer
      // (multiple `sources` become BANDS of one image, asserted to share an origin).
      // The per-island entries stay, carrying each island's bbox and published
      // figures — they are what a viewport-scoped readout will sum.
      out[id] = {
        title: layer.title,
        asset: resolve(indexUrl, layer.asset),
        stats: layer.stats || {},
        islands: layer.islands || {},
      };
    }
    return out;
  }
  return loadCatalogFromStac();
}

/** The original 64-request walk, kept as a fallback. */
async function loadCatalogFromStac() {
  let rootUrl = null, root = null;
  for (const candidate of DATA_CANDIDATES) {
    try {
      rootUrl = new URL(`${candidate}/catalog.json`, location.href).href;
      root = await json(rootUrl);
      DATA = candidate;
      break;
    } catch { /* try the next layout */ }
  }
  if (!root) throw new Error('no catalogue found in ' + DATA_CANDIDATES.join(' or '));
  const out = {};
  for (const link of root.links.filter((l) => l.rel === 'child')) {
    const colUrl = resolve(rootUrl, link.href);
    const col = await json(colUrl);
    const islands = {};
    let asset = null;
    for (const itemLink of col.links.filter((l) => l.rel === 'item')) {
      const itemUrl = resolve(colUrl, itemLink.href);
      const item = await json(itemUrl);
      // Every item now names the same archipelago asset, so the walk collapses to
      // one URL — taking it from whichever item we see first is correct, not a guess.
      asset = resolve(itemUrl, item.assets.data.href);
      islands[item.properties.island] = {
        stats: item.properties['sensisat:statistics'] || {},
        bbox: item.bbox,
      };
    }
    out[col.id] = {title: col.title, asset, stats: {}, islands};
  }
  return out;
}

/* -------------------------------------------------------------------- style */
/**
 * Colour expressions.
 *
 * One rule governs the shape of everything here: **only numbers may be style
 * variables; colours must be literals.** OpenLayers compiles `['var', x]` to a
 * `uniform float`, so putting a colour in a variable makes the fragment shader
 * fail to compile with "mismatching ternary operator operand types 'uniform highp
 * float' and 'const 4-component vector of float'" — and the map then renders
 * nothing at all, basemap included, with the failure only visible in the console.
 *
 * So the year window travels as two numbers (`lo`, `hi`) and the mode as a third
 * (`since`), and every branch below returns a literal vec4.
 */
const NONE = [0, 0, 0, 0];

function colourFor(name) {
  const def = LAYERS[name];
  const band = ['band', 1];

  if (def.kind === 'year' || def.kind === 'epoch') {
    const undated = def.kind === 'year'
      // "Built, year unknown" is a real third state, never a guess — but it cannot
      // belong to a period either, so the "added since" view must not claim it.
      ? [['==', band, UNDATED], ['case', ['==', ['var', 'since'], 1], NONE, C.undated]]
      : [];
    return ['case',
      ['==', band, 0], NONE,
      ...undated,
      ['<', band, ['var', 'lo']], NONE,
      ['>', band, ['var', 'hi']], NONE,
      ['==', ['var', 'since'], 1], C.added,
      C.built];
  }
  if (def.kind === 'binary') {
    return ['case', ['>', band, 0], C.green, NONE];
  }
  if (def.kind === 'percent') {
    return ['case', ['<=', band, 0], NONE,
      ['interpolate', ['linear'], band,
        1, [255, 245, 200, 0.75],
        30, [255, 190, 90, 0.85],
        60, [240, 120, 50, 0.92],
        100, [150, 25, 20, 1]]];
  }
  if (def.kind === 'trend') {
    return ['case', ['<=', band, 0], NONE,
      ['interpolate', ['linear'], band,
        1, [255, 245, 200, 0.7],
        1500, [255, 180, 70, 0.85],
        4000, [230, 100, 40, 0.92],
        8500, [140, 20, 20, 1]]];
  }
  if (def.kind === 'change') {
    return ['case',
      ['==', band, 1], C.gain,
      ['==', band, 2], C.loss,
      ['==', band, 11], [120, 190, 255, 0.85],
      ['==', band, 12], [255, 150, 150, 0.85],
      ['==', band, 10], [110, 130, 150, 0.35],
      NONE];
  }
  return ['case', ['>', band, 0], C.built, NONE];
}

/** Slider year -> WSF Tracker epoch. One rule, used by the shader and the readout. */
const toEpoch = (y) => Math.max(1, Math.min(20, Math.round((y - 2016) / 0.5)));

/** The epoch's published name, e.g. 2016-07. Falls back to the raw number. */
function epochLabel(e) {
  return state.catalog?.[state.layer]?.stats?.epoch_labels?.[e] ?? e;
}

/** Numeric style variables. Changing these re-renders on the GPU and fetches nothing. */
function variables() {
  const def = LAYERS[state.layer];
  const since = state.mode === 'since' ? 1 : 0;

  if (def.kind === 'year') {
    const enc = (y) => y - YEAR_OFFSET;
    return since
      ? {lo: enc(state.sinceYear) + 1, hi: UNDATED - 1, since}
      : {lo: 1, hi: enc(state.year), since};
  }
  if (def.kind === 'epoch') {
    return since
      ? {lo: toEpoch(state.sinceYear) + 1, hi: 20, since}
      : {lo: 1, hi: toEpoch(state.year), since};
  }
  return {lo: 0, hi: 255, since: 0};
}

