/** The year the aerial photograph should show: whatever the slider points at. */
function activeYear() {
  const def = LAYERS[state.layer];
  if (!def || !['year', 'epoch', 'trend'].includes(def.kind)) return PNOA_LAST_YEAR;
  return sliderYear();
}

/** Keep the year-following aerial in step with the slider. */
function syncBasemapYear() {
  if (activeBasemap() !== 'pnoaYear') return;
  const wanted = `PNOA${pnoaYearFor(activeYear())}`;
  const source = baseLayer().getSource();
  if (source?.getParams && source.getParams().LAYERS !== wanted) {
    source.updateParams({LAYERS: wanted});
  }
  const asked = Math.round(activeYear());
  const shown = pnoaYearFor(asked);
  el('basemap-note').textContent = shown === asked
    ? `Aerial photograph from ${shown}.`
    : `Aerial photograph from ${shown} — the nearest PNOA flight. The Canaries are `
      + `photographed about every three years (${PNOA_YEARS.join(', ')}), not annually.`;
}

/**
 * Say so when the view has gone deeper than the basemap has pictures for.
 *
 * Without this the map looks broken: the layer draws correctly over a background
 * that has quietly stopped carrying information, and there is nothing on screen to
 * say which of the two is at fault. Being stretched is the right behaviour — it
 * beats a wall of "Map data not yet available" — but only if the reader is told.
 */
function syncBasemapNote() {
  if (activeBasemap() === 'pnoaYear') { syncBasemapYear(); return; }
  const b = BASEMAPS[activeBasemap()];
  const deeper = Object.values(BASEMAPS)
    .filter((o) => o !== b && (o.maxZoom ?? 99) > (b?.maxZoom ?? 99))
    .map((o) => o.title);
  el('basemap-note').textContent =
    b?.maxZoom != null && map.getView().getZoom() > b.maxZoom + 0.5
      ? `The ${b.title} basemap has no more detail at this zoom and is being stretched.`
        + (deeper.length
            ? ` ${deeper.slice(0, -1).join(', ')}${deeper.length > 1 ? ' and ' : ''}`
              + `${deeper[deeper.length - 1]} go deeper.`
            : '')
      : '';
}

const base = new TileLayer({source: basemapSource('light')});

/**
 * The view is EPSG:4326 — the projection our COGs are already in — and NOT the
 * usual EPSG:3857. This is forced, not a preference: a WebGLTileLayer cannot
 * reproject, so a GeoTIFF source whose projection differs from the view simply
 * never renders, with no error to say why. The basemap is the piece that gets
 * reprojected instead, which an ordinary raster TileLayer does support.
 */
const map = new OLMap({
  target: 'map', layers: [base],
  view: new View({projection: 'EPSG:4326', center: [-15.6, 28.0], zoom: 9, maxZoom: 19}),
});
let dataLayer = null;

async function showLayer() {
  const entry = state.catalog[state.layer];
  if (!entry?.asset) { status(`no data published for ${state.layer}`, true); return; }
  status('loading raster…');
  // Before the raster: the figures come from index.json, which is already in memory,
  // so they never needed to wait for it. Leaving them alone until the COG resolved
  // meant the PREVIOUS layer's number sat under the new layer's name for about a
  // second — a figure from one layer displayed beside another, which is the kind of
  // stale-number problem this project spends most of its gates preventing.
  renderLegend();
  renderReadout(scope());

  const def = LAYERS[state.layer];
  const bandIndex = def.kind === 'trend' ? def.epochs.indexOf(state.year) + 1 : 1;

  const source = new GeoTIFF({
    sources: [{url: entry.asset, bands: [bandIndex || 1], nodata: 0}],
    normalize: false, interpolate: false, convertToRGB: false,
  });
  const layer = new WebGLTileLayer({
    source, style: {color: colourFor(state.layer), variables: variables()}, opacity: 0.92,
  });

  if (dataLayer) map.removeLayer(dataLayer);
  dataLayer = layer;
  map.addLayer(layer);

  source.on('error', (e) => status(`raster error: ${e.error?.message || e.message}`, true));
  try {
    const view = await source.getView();
    map.getView().fit(entry.bbox ?? view.extent, {padding: [30, 30, 30, 30], duration: 350});
    status(`${def.title} — Canary Islands`);
  } catch (err) {
    console.error(err);
    status(`could not read the raster: ${err.message}`, true);
  }
  renderLegend();
  renderReadout(scope());
  // fit() animates, so its moveend arrives on its own; this covers the case where
  // the view does not move at all because the new layer has the same extent.
  scheduleScope(400);
}

function restyle() {
  if (!dataLayer) return;
  const def = LAYERS[state.layer];
  if (def.kind === 'trend') { showLayer(); return; }   // a different band, so a new read
  dataLayer.updateStyleVariables(variables());
  renderReadout(scope());
}

/* ------------------------------------------------------------------ panel */
/** Whichever year the slider is currently pointing at, given the mode. */
function sliderYear() {
  const def = LAYERS[state.layer];
  return state.mode === 'since' && def.kind !== 'trend' ? state.sinceYear : state.year;
}

/** Warn when the slider sits in the part of the cadastre that was bucketed. */
function precisionNote() {
  if (state.layer !== 'buildings-dated') return '';
  const y = Math.round(sliderYear());
  if (y > CADASTRE_BUCKETED_UNTIL) return '';
  if (CADASTRE_MAJOR_BUCKETS.has(y)) {
    return `⚠ ${y} is one of the ten years the cadastre used for "old, date unknown". `
         + `Together they hold a third (33.8 %) of all dated buildings, so read this frame as `
         + `"by about ${y}" rather than as ${y} exactly.`;
  }
  return `Before ${CADASTRE_BUCKETED_UNTIL} the cadastre rounded many unknown dates onto `
       + `whole decades, so this frame is reliable to roughly a decade. Years that are `
       + `not round are genuine.`;
}

function modeNote() {
  if (state.mode !== 'since') return '';
  return `Showing only what appeared after ${state.sinceYear}. Two states side by side hide `
       + `change: Gran Canaria grew ${FACTS.gc_growth_1995_2015_pct} % between 1995 and 2015 and the two maps look identical.`;
}

function renderLegend() {
  const def = LAYERS[state.layer];
  const key = (colour, label) =>
    `<div class="key"><span class="sw" style="background:rgba(${colour[0]},${colour[1]},${colour[2]},${colour[3]})"></span><span>${label}</span></div>`;
  const ramp = (stops, label) =>
    `<div class="key"><span class="ramp" style="background:linear-gradient(90deg,${stops})"></span></div><div class="cap">${label}</div>`;

  let html = '';
  if (def.kind === 'year' || def.kind === 'epoch') {
    if (state.mode === 'since') {
      html += key(C.added, `Appeared after ${state.sinceYear}`);
      // The undated class is deliberately absent here: a pixel with no year cannot
      // be placed in a period, so the change view must not imply that it can.
      if (def.kind === 'year') html += `<div class="cap">Undated pixels are hidden — they cannot be assigned to a period.</div>`;
    } else {
      html += key(C.built, `Built by ${state.year}`);
      if (def.kind === 'year') html += key(C.undated, 'Built, year unknown');
    }
  } else if (def.kind === 'binary') {
    html += key(C.green, 'Greenhouse parcel');
  } else if (def.kind === 'percent') {
    html += ramp('rgba(255,245,200,.8),rgba(255,190,90,.9),rgba(240,120,50,.95),rgba(150,25,20,1)', '1 % → 100 % of the pixel sealed');
  } else if (def.kind === 'trend') {
    html += ramp('rgba(255,245,200,.8),rgba(255,180,70,.9),rgba(230,100,40,.95),rgba(140,20,20,1)', `m² built per cell, ${state.year}`);
  } else if (def.kind === 'change') {
    html += key(C.gain, 'New built-up cover') + key(C.loss, 'Loss of cover')
         + key([110, 130, 150, 0.6], 'Unchanged built-up');
  }
  el('legend').innerHTML = html;
}

/**
 * Format an area for display, in the READER's number convention.
 *
 * Raw JavaScript prints 2.343 and 7344.65, which is the English convention and
 * ambiguous everywhere that uses "." to group thousands — Spain and most of the
 * continent, which is to say much of this map's audience. A Spanish planner reading
 * "2.343 km²" sees two thousand.
 *
 * The locale must be `navigator.languages`, NOT omitted. Measured in Chrome with
 * navigator.language = "es-ES": `Intl.NumberFormat(undefined)` resolves to en-US,
 * because the runtime default follows the browser's UI language rather than the
 * user's content preferences. Passing the preference list explicitly is what
 * actually honours it.
 *
 * Two decimals, always. These are square kilometres of an island, so a third
 * decimal is 1000 m² of precision nobody is reading. The one consequence worth
 * knowing: a change smaller than 0.005 km² prints as 0, which only the loss layer
 * can produce.
 */
const area = (n) => n == null || !isFinite(n) ? '—'
  : new Intl.NumberFormat(navigator.languages, {maximumFractionDigits: 2}).format(n);

/* ------------------------------------------------- what is on screen, counted */
/**
 * Full-resolution handles, one per published file.
 *
 * Opening a COG costs one range request for its header, and every window read
 * afterwards reuses it — so this map is what stops a pan from re-reading the header
 * each time. `getImage(0)` is deliberate: image 0 is the full-resolution image and
 * 1..n are the overviews, and the readout must never count an overview (see
 * count.js for the 104.3 -> 3,310.3 km2 this avoids).
 */
const images = new Map();
const fullResImage = (url) => {
  if (!images.has(url)) images.set(url, fromUrl(url).then((t) => t.getImage(0)));
  return images.get(url);
};

/**
 * Decode workers.
 *
 * A COG is stored in compressed 1024 x 1024 blocks, so even a small window inflates
 * more than a million pixels, and a view covering most of an island inflates tens of
 * millions. On the main thread that is a visibly frozen page — measured here by
 * freezing it. geotiff.js takes a worker pool and does the inflating off-thread.
 *
 * Measured worth on the published mosaic, a 25 km view over Tenerife: 533 and
 * 601 ms with the pool against 616, 878 and 1,013 ms without. geotiff.js embeds the
 * worker source and builds it from a Blob, so it survives bundling — which is not
 * obvious, and is why the numbers are written down here.
 *
 * Created lazily and guarded: worker construction is the kind of thing a bundler or
 * a strict CSP can break, and a readout that is merely slower is better than one
 * that throws. If it cannot be built we decode in place, as before.
 */
let decodePool;
function pool() {
  if (decodePool === undefined) {
    try { decodePool = new Pool(); } catch (err) { console.warn('no decode pool', err); decodePool = null; }
  }
  return decodePool || undefined;
}

/**
 * The pixel window covering a map extent, clipped to the file.
 *
 * Returns null when the view and the file share no ground — which is a real answer
 * (the sea holds no buildings), not a failure. `north` comes back because turning
 * pixels into square kilometres needs the latitude of the window's top EDGE, and
 * recovering it later from the extent rather than from the window would reintroduce
 * exactly the fractional-window offset of CLAUDE.md #25.
 */
function windowFor(image, extent) {
  const [w, s, e, n] = image.getBoundingBox();
  const width = image.getWidth(), height = image.getHeight();
  const px = (e - w) / width, py = (n - s) / height;

  const left = Math.max(0, Math.floor((extent[0] - w) / px));
  const right = Math.min(width, Math.ceil((extent[2] - w) / px));
  const top = Math.max(0, Math.floor((n - extent[3]) / py));
  const bottom = Math.min(height, Math.ceil((n - extent[1]) / py));
  if (right <= left || bottom <= top) return null;

  return {left, top, right, bottom, pixelDeg: py, north: n - top * py,
          width: right - left, height: bottom - top,
          pixels: (right - left) * (bottom - top)};
}

/**
 * The year or epoch keys to report, taken from what the build published.
 *
 * Emitting the published keys rather than a range of this file's own choosing is
 * what lets the counted answer and the summed answer be compared key by key — and
 * it is the difference between a readout that agrees with the page and one that
 * merely looks similar.
 */
function seriesKeys(entry, def) {
  const s = entry.stats || {};
  const nums = (o) => Object.keys(o || {}).map(Number).sort((a, b) => a - b);
  if (def.kind === 'year') return {years: nums(s.extent_by_year)};
  if (def.kind === 'epoch') return {epochs: nums(s.extent_by_epoch)};
  return {};
}

/**
 * Recompute what the readout describes, for the view as it now stands.
 *
 * Two regimes (count.js holds the choice and the arithmetic). Small views read the
 * real pixels; large ones sum the published figures of the islands they touch. The
 * caption says which, because the number genuinely means different things.
 *
 * `token` guards against a slow read landing after a faster, later one: panning
 * fires several of these, and the answer that arrives last is not necessarily the
 * answer to the view the user is looking at.
 */
let scopeToken = 0;
let moveTimer = null;

async function updateScope() {
  const token = ++scopeToken;
  const entry = state.catalog?.[state.layer];
  if (!entry) return;
  const def = LAYERS[state.layer];
  const extent = map.getView().calculateExtent(map.getSize());
  const names = islandsInView(extent, entry.islands || {});
  const total = Object.keys(entry.islands || {}).length;

  const settle = (scope) => {
    if (token !== scopeToken) return;      // a later view has already superseded this
    state.scope = scope;
    renderReadout(scope);
  };
  const zero = () => (FAR_ONLY_KINDS.has(def.kind) ? {} : emptyStats(def.kind, seriesKeys(entry, def)));
  const far = () => ({
    regime: 'far',
    label: describe('far', names, total),
    stats: names.length ? sumStats(names.map((n) => entry.islands[n].stats)) : zero(),
  });

  // No table means no honest way to turn pixels into square kilometres, so the
  // counting path is simply unavailable — never approximated.
  if (FAR_ONLY_KINDS.has(def.kind) || !state.areaTable) { settle(far()); return; }

  // If the count is quick, the readout updates once and the reader sees no
  // intermediate state. If it is not, the island figure goes up rather than leaving
  // the PREVIOUS view's number sitting there — it is correct, merely coarser, and
  // its caption says which islands it covers. The counted answer then replaces it.
  const slow = setTimeout(() => settle(far()), 250);
  try {
    const image = await fullResImage(entry.asset);
    if (token !== scopeToken) { clearTimeout(slow); return; }
    const win = windowFor(image, extent);
    if (!win) {
      clearTimeout(slow);
      settle({regime: 'near', label: describe('near', names, total), stats: zero()});
      return;
    }
    // The budget is in BLOCKS because that is the unit a COG is read in — a window
    // smaller than one block still costs a whole one. blockSpan() measures the
    // window's SIZE, never its alignment, so panning at a fixed zoom cannot change
    // which regime answers (see count.js).
    const tile = {width: image.getTileWidth(), height: image.getTileHeight()};
    if (regimeFor(def.kind, blockSpan(win, tile)) !== 'near') {
      clearTimeout(slow);
      settle(far());
      return;
    }

    // Band 1 for every layer with a near path; only density-trend is multi-band and
    // it is far-only. geotiff.js counts samples from 0, OpenLayers from 1.
    const [values] = await image.readRasters({
      window: [win.left, win.top, win.right, win.bottom], samples: [0], pool: pool(),
    });
    clearTimeout(slow);
    const areas = rowAreas(state.areaTable, win);
    const hist = areaHistogram(values, {width: win.width, height: win.height, areas});
    settle({regime: 'near', label: describe('near', names, total),
            stats: statsFromHistogram(hist, {kind: def.kind, ...seriesKeys(entry, def)})});
  } catch (err) {
    // A failed read must not blank the number. The island sums are honest because
    // the caption then names the islands rather than claiming to describe the screen.
    clearTimeout(slow);
    console.error(err);
    settle(far());
  }
}

/** Panning fires a burst of these; only the view it settles on is worth reading. */
function scheduleScope(delay = 150) {
  clearTimeout(moveTimer);
  moveTimer = setTimeout(updateScope, delay);
}

/**
 * What the readout is describing, right now and synchronously.
 *
 * Until a view has been measured this is the whole archipelago, which is both true
 * at first paint and instantly available — the figures are already in index.json.
 * updateScope() then replaces it. Every caption below reads `label` and never asks
 * how the number was reached.
 */
function scope() {
  if (state.scope) return state.scope;
  const layer = state.catalog?.[state.layer];
  return {regime: 'far', label: 'all eight islands', stats: layer?.stats || {}};
}


function renderReadout(entry) {
  const def = LAYERS[state.layer];
  const s = entry?.stats || {};

  // The trend layer's number is per epoch, and the loss layer's is per period —
  // neither has a single "how much is there" figure, so each says what it has.
  if (def.kind === 'trend' && s.surface_km2) {
    const now = s.surface_km2[state.year], first = s.surface_km2[def.epochs[0]];
    const growth = first ? Math.round(100 * (now / first - 1)) : null;
    el('readout').innerHTML = `<div class="big">${area(now)} km²</div>`
      + `<div class="cap">built surface in ${state.year}`
      + (growth == null ? '' : ` · ${growth >= 0 ? '+' : ''}${growth} % since ${def.epochs[0]}`)
      + ` · ${s.observed?.[state.year] ?? ''}</div>`;
    return;
  }
  if (def.kind === 'change' && s.change_km2) {
    const rows = Object.entries(s.change_km2).map(([period, v]) =>
      `<div class="cap">${period}: <b>+${area(v.new_cover_km2)}</b> km² new, <b>−${area(v.loss_of_cover_km2)}</b> km² lost</div>`).join('');
    el('readout').innerHTML = `<div class="cap">Built-up change, ${entry.label}</div>${rows}`;
    return;
  }

  // A number that does not move while the map visibly does reads as a bug, so the
  // time-varying layers report the extent at the year on the slider, not their
  // whole-island total. Undated pixels are not in these series — they are built but
  // cannot be placed in a year — so the caption says so rather than quietly
  // dropping them.
  if (def.kind === 'year' && s.extent_by_year) {
    const yrs = Object.keys(s.extent_by_year).map(Number);
    const clamp = (v) => Math.min(Math.max(v, Math.min(...yrs)), Math.max(...yrs));
    // "Added since" is a SUBTRACTION of two cumulative totals, and the readout has to
    // do it too. The map in this mode draws only what appeared after the slider year;
    // a readout still showing the running total describes a different picture from
    // the one on screen, which is the whole thing C4 exists to stop. Both regimes get
    // it free: the series is already in memory, near or far.
    if (state.mode === 'since') {
      const added = addedSince(s.extent_by_year, state.sinceYear);
      el('readout').innerHTML = `<div class="big">${area(added)} km²</div>`
        + `<div class="cap">${def.title.toLowerCase()} appearing after ${state.sinceYear}, `
        + `${entry.label} · undated ground is excluded, it cannot be placed in a period</div>`;
      return;
    }
    const y = clamp(state.year);
    const now = s.extent_by_year[y];
    const undated = s.undated_km2 ?? s['pre-2016, undated'];
    // VISIBLE, not merely non-zero. area() prints two decimals, so a scope holding
    // 0.000088 km² of undated ground produced "plus 0 km² built but undated" — a
    // clause that says nothing while looking like a figure. The threshold is the
    // smallest value that prints as anything other than zero.
    const showUndated = undated != null && undated >= 0.005;
    el('readout').innerHTML = `<div class="big">${area(now)} km²</div>`
      + `<div class="cap">${def.title.toLowerCase()} by ${state.year}, ${entry.label}`
      + (showUndated ? ` · plus ${area(undated)} km² built but undated` : '') + '</div>';
    return;
  }
  if (def.kind === 'epoch' && s.extent_by_epoch) {
    if (state.mode === 'since') {
      // Within era-b only. Epoch 1 is the July-2016 baseline, so "since epoch 1" means
      // everything built after it — a subtraction inside ONE era, never across the
      // 2015/2016 seam, which the two layers share as a baseline (decision 13).
      const from = toEpoch(state.sinceYear);
      const added = addedSince(s.extent_by_epoch, from);
      el('readout').innerHTML = `<div class="big">${area(added)} km²</div>`
        + `<div class="cap">${def.title.toLowerCase()} appearing after `
        + `${epochLabel(from)}, ${entry.label}</div>`;
      return;
    }
    const e = toEpoch(state.year);
    const label = epochLabel(e);
    el('readout').innerHTML = `<div class="big">${area(s.extent_by_epoch[e])} km²</div>`
      + `<div class="cap">${def.title.toLowerCase()} by ${label}, ${entry.label}`
      + (s.greenhouse_removed_km2 ? ` · ${area(s.greenhouse_removed_km2)} km² of greenhouses removed` : '')
      + '</div>';
    return;
  }

  const km2 = s.footprint_km2 ?? s.area_km2 ?? s.sealed_km2 ?? null;
  let extra = '';
  if (s['pre-2016, undated'] != null) extra = `${s['dated_share_pct']} % of it carries a year`;
  else if (s.greenhouse_removed_km2 != null) extra = `${area(s.greenhouse_removed_km2)} km² of greenhouses removed`;
  else if (s.survey_year) extra = `surveyed ${s.survey_year}`;
  el('readout').innerHTML = km2 == null ? ''
    : `<div class="big">${area(km2)} km²</div><div class="cap">${def.title.toLowerCase()}, ${entry.label}${extra ? ' · ' + extra : ''}</div>`;
}

function syncTimeControls() {
  const def = LAYERS[state.layer];
  const timed = ['year', 'epoch', 'trend'].includes(def.kind);
  el('time-controls').style.display = timed ? '' : 'none';
  el('layer-note').textContent = def.note || '';
  el('seam-note').textContent = def.seam || '';
  if (!timed) { renderLegend(); return; }

  const slider = el('year');
  if (def.kind === 'trend') {
    slider.min = 0; slider.max = def.epochs.length - 1; slider.step = 1;
    slider.value = def.epochs.indexOf(state.year);
    el('tick-min').textContent = def.epochs[0];
    el('tick-max').textContent = def.epochs.at(-1);
  } else if (def.kind === 'epoch') {
    // WSF Tracker runs twice a year, so a whole-year step reaches only half the
    // epochs — and rounding 2016.5 up put epoch 1, the July 2016 baseline this
    // layer's own note describes, out of reach entirely.
    slider.min = def.min; slider.max = def.max; slider.step = 0.5;
    slider.value = sliderYear();
    el('tick-min').textContent = epochLabel(toEpoch(def.min));
    el('tick-max').textContent = epochLabel(toEpoch(def.max));
  } else {
    slider.min = Math.ceil(def.min); slider.max = Math.floor(def.max); slider.step = 1;
    slider.value = sliderYear();
    el('tick-min').textContent = Math.ceil(def.min);
    el('tick-max').textContent = Math.floor(def.max);
  }
  // A half-year reads as "2016.5" unless it is named, which is what the epoch
  // labels published with the layer are for.
  el('year-out').textContent = def.kind === 'epoch'
    ? epochLabel(toEpoch(sliderYear())) : sliderYear();
  el('mode-note').textContent = modeNote();
  el('precision-note').textContent = precisionNote();
}

/* ------------------------------------------------------------------- wiring */
function setLayer(name) {
  state.layer = name;
  // The previous layer's measurement describes the previous layer. Clearing it makes
  // scope() fall back to this layer's published archipelago total — true, instant,
  // and replaced as soon as the view is measured. Keeping it would put one layer's
  // number under another layer's name, which is the defect commit 8631160 fixed in
  // its other form.
  state.scope = null;
  const def = LAYERS[name];
  if (def.kind === 'trend') state.year = def.start;
  else if (def.kind === 'year' || def.kind === 'epoch') state.year = Math.floor(def.start ?? def.max);
  state.sinceYear = def.kind ? Math.floor(((def.min ?? 1900) + (def.max ?? 2020)) / 2) : 2000;
  syncTimeControls();
  showLayer();
}

function init(catalog) {
  state.catalog = catalog;
  const layerSel = el('layer');

  // The readout follows the map. `moveend` rather than `change:center` because a
  // pan fires hundreds of the latter, and the only view worth measuring is the one
  // the user stops on; the debounce then absorbs a flick of the wheel.
  map.on('moveend', () => { scheduleScope(); syncBasemapNote(); });

  layerSel.innerHTML = Object.entries(LAYERS)
    .filter(([id]) => catalog[id])
    .map(([id, d]) => `<option value="${id}">${d.title}</option>`).join('');
  layerSel.value = state.layer;

  const basemapBox = el('basemaps');
  basemapBox.innerHTML = Object.entries(BASEMAPS)
    .map(([k, b], i) => `<button data-base="${k}"${i === 0 ? ' class="on"' : ''}>${b.title}</button>`).join('');
  basemapBox.querySelectorAll('button').forEach((b) => {
    b.onclick = () => {
      basemapBox.querySelectorAll('button').forEach((x) => x.classList.remove('on'));
      b.classList.add('on');
      state.basemap = b.dataset.base;
      el('basemap-note').textContent = '';
      baseLayer().setSource(basemapSource(b.dataset.base));
      syncBasemapNote();
      map.renderSync();
    };
  });

  layerSel.onchange = () => setLayer(layerSel.value);

  // Scoped to #viewmodes, NOT to `.modes button`. The basemap switcher reuses the
  // `.modes` class for its styling, so the broad selector matched those buttons too
  // and this loop overwrote their click handlers — clicking "Aerial" ran the
  // view-mode handler, which lit the button, left the basemap untouched, and set
  // state.mode to undefined. Style classes must never be used as behaviour selectors.
  const viewModes = el('viewmodes');
  viewModes.querySelectorAll('button').forEach((b) => {
    b.onclick = () => {
      viewModes.querySelectorAll('button').forEach((x) => x.classList.remove('on'));
      b.classList.add('on');
      state.mode = b.dataset.mode;
      syncTimeControls(); restyle(); renderLegend();
    };
  });

  el('year').oninput = (e) => {
    const def = LAYERS[state.layer];
    const value = def.kind === 'trend' ? def.epochs[+e.target.value] : +e.target.value;
    // The slider means "up to this year" in state mode and "since this year" in
    // change mode. One control, because the user is always pointing at one year.
    if (state.mode === 'since' && def.kind !== 'trend') state.sinceYear = value;
    else state.year = value;
    // syncTimeControls names epochs; the live handler has to do the same or the
    // label reverts to a bare "2016.5" as soon as the slider moves.
    el('year-out').textContent = def.kind === 'epoch' ? epochLabel(toEpoch(value)) : value;
    el('mode-note').textContent = modeNote();
    el('precision-note').textContent = precisionNote();
    syncBasemapYear();
    restyle(); renderLegend();
  };

  el('play').onclick = () => {
    const btn = el('play');
    if (state.playing) { clearInterval(state.playing); state.playing = null; btn.classList.remove('on'); btn.innerHTML = '&#9658;'; return; }
    btn.classList.add('on'); btn.innerHTML = '&#10073;&#10073;';
    const slider = el('year');
    state.playing = setInterval(() => {
      let v = +slider.value + 1;
      if (v > +slider.max) v = +slider.min;
      slider.value = v; slider.dispatchEvent(new Event('input'));
    }, 130);
  };

  setLayer(state.layer);

  // Exposed for debugging and for driving the viewer from a test harness. The
  // module scope is otherwise closed, so there is no other way to inspect what the
  // map is actually doing from outside.
  window.sensisat = {map, state, LAYERS, showLayer, restyle, updateScope, scope,
                     get layer() { return dataLayer; }};
}

