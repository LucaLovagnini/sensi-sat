/**
 * Basemaps.
 *
 * Two of these are aerial photography, and that is the point: the fastest way to
 * tell whether a flagged pixel is a real building — or whether a real building was
 * missed — is to look at a photograph of the ground.
 *
 * **PNOA** is Spain's national orthophoto programme at 12–25 cm, an order of
 * magnitude sharper than the global satellite mosaics, and it is served natively
 * in EPSG:4326, so it needs no reprojection and stays crisp. It is also the exact
 * imagery M3's accuracy assessment will be interpreted from, which means checking
 * a layer against it here is checking it against the reference.
 *
 * **PNOA at the slider year** is the one worth knowing about. The historical
 * service publishes a separate layer per year, PNOA2004 to PNOA2024, so the
 * photograph underneath can follow the time slider: set the year to 2010 and you
 * are comparing what we say was built by 2010 against what the aeroplane saw in
 * 2010. Outside that range it clamps to the nearest available year and says so.
 *
 * Esri's global mosaic stays as the fallback that works outside Spain, which
 * matters the day this is pointed at anywhere else.
 */
/**
 * The cadastre bucketed unknown construction dates onto round years until 1980.
 * Measured (analysis 19), and the buckets are NOT all alike:
 *
 *   10 major buckets  1900, 1910, 1920, 1930, 1940, 1950, 1960, 1970, 1975, 1980
 *                     158,658 buildings — 33.8 % of every dated building. 1900
 *                     alone holds 25,971, the largest single year in the register.
 *    5 minor buckets  1905, 1915, 1925, 1935, 1945
 *                     4,471 buildings between them — 0.95 %. Statistically visible
 *                     (3–5x their neighbours) but practically invisible: 1915 adds
 *                     38 buildings to Santa Cruz de Tenerife, a city of 23,881.
 *
 * Only the major ones are called out. Warning about a year that moves 0.07 % of the
 * data would train the reader to ignore the warning that matters.
 *
 * After 1980 there is not one spike in 46 years, so dates from 1981 on are good to
 * the year. Before it they are good to about a decade — but 37 % of pre-1981
 * buildings do carry a genuine year, which is why the slider still moves a year at
 * a time rather than snapping to five.
 */
const CADASTRE_BUCKETED_UNTIL = 1980;
const CADASTRE_MAJOR_BUCKETS = new Set([1900, 1910, 1920, 1930, 1940, 1950, 1960, 1970, 1975, 1980]);

/**
 * PNOA flies the Canaries roughly every three years, not annually. Measured over
 * Gran Canaria: only these years return imagery; every other layer between 2004
 * and 2024 returns a blank white frame. Offering a year with no flight looked like
 * a working basemap that had gone white, which is worse than not offering it.
 */
const PNOA_YEARS = [2005, 2009, 2012, 2015, 2018, 2021, 2024];
const PNOA_FIRST_YEAR = PNOA_YEARS[0];
const PNOA_LAST_YEAR = PNOA_YEARS[PNOA_YEARS.length - 1];

